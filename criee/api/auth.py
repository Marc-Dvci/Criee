"""Sessions, passkeys and device keys.

A wish is signed by the person's own authenticator. The WebAuthn challenge is the SHA-256 of the
canonical wish terms, so the stored assertion proves consent to those exact terms. Browsers without a
passkey can sign with a non-extractable P-256 key generated by WebCrypto.
"""
from __future__ import annotations

import base64
import hashlib
import hmac
import json
from typing import Optional
from urllib.parse import urlparse

from cryptography.exceptions import InvalidSignature
from cryptography.hazmat.primitives import hashes
from cryptography.hazmat.primitives.asymmetric import ec
from cryptography.hazmat.primitives.asymmetric.utils import encode_dss_signature
from fastapi import HTTPException, Request, Response
from webauthn import (generate_authentication_options, generate_registration_options, options_to_json,
                      verify_authentication_response, verify_registration_response)
from webauthn.helpers import base64url_to_bytes, bytes_to_base64url
from webauthn.helpers.structs import (AuthenticatorSelectionCriteria, PublicKeyCredentialDescriptor,
                                      ResidentKeyRequirement, UserVerificationRequirement)

from ..core import Account, Core

COOKIE = "criee_session"


def b64u(b: bytes) -> str:
    return base64.urlsafe_b64encode(b).rstrip(b"=").decode()


def _mac(secret: str, value: str) -> str:
    return hmac.new(secret.encode(), value.encode(), hashlib.sha256).hexdigest()[:32]


def set_session(resp: Response, core: Core, account_id: str, secure: bool) -> None:
    resp.set_cookie(COOKIE, f"{account_id}.{_mac(core.cfg.session_secret, account_id)}", httponly=True,
                    samesite="lax", secure=secure, max_age=60 * 60 * 24 * 60)


def current(request: Request, core: Core) -> Optional[Account]:
    raw = request.cookies.get(COOKIE) or ""
    auth = request.headers.get("authorization", "")
    if auth.lower().startswith("bearer "):
        token = auth[7:].strip()
        aid = core.ledger.kv_get(f"agent_token:{hashlib.sha256(token.encode()).hexdigest()}")
        return core.accounts.get(aid) if aid else None
    if "." not in raw:
        return None
    aid, mac = raw.rsplit(".", 1)
    if not hmac.compare_digest(mac, _mac(core.cfg.session_secret, aid)):
        return None
    return core.accounts.get(aid)


def require(request: Request, core: Core, role: Optional[str] = None) -> Account:
    acc = current(request, core)
    if acc is None:
        raise HTTPException(401, "start a session first")
    if role and role not in acc.roles:
        raise HTTPException(403, f"this needs the {role} role")
    return acc


def rp(core: Core, request: Request) -> tuple[str, str]:
    origin = request.headers.get("origin") or core.cfg.public_url
    host = urlparse(origin).hostname or "localhost"
    return core.cfg.rp_id or host, origin


def credentials(core: Core, account_id: str) -> list[dict]:
    raw = core.ledger.kv_get(f"creds:{account_id}")
    return json.loads(raw) if raw else []


def _save_cred(core: Core, account_id: str, cred: dict) -> None:
    creds = [c for c in credentials(core, account_id) if c["id"] != cred["id"]] + [cred]
    core.ledger.kv_set(f"creds:{account_id}", json.dumps(creds))


# ----------------------------------------------------------------------------- passkeys

def registration_options(core: Core, request: Request, acc: Account) -> dict:
    rp_id, _ = rp(core, request)
    opts = generate_registration_options(
        rp_id=rp_id, rp_name="Criée", user_id=acc.id.encode(), user_name=acc.handle, user_display_name=acc.handle,
        authenticator_selection=AuthenticatorSelectionCriteria(resident_key=ResidentKeyRequirement.PREFERRED,
                                                               user_verification=UserVerificationRequirement.PREFERRED),
        exclude_credentials=[PublicKeyCredentialDescriptor(id=base64url_to_bytes(c["id"]))
                             for c in credentials(core, acc.id) if c["kind"] == "passkey"])
    core.ledger.kv_set(f"reg_challenge:{acc.id}", bytes_to_base64url(opts.challenge))
    return json.loads(options_to_json(opts))


def registration_verify(core: Core, request: Request, acc: Account, credential: dict) -> dict:
    rp_id, origin = rp(core, request)
    challenge = core.ledger.kv_get(f"reg_challenge:{acc.id}")
    if not challenge:
        raise HTTPException(400, "no registration in progress")
    try:
        v = verify_registration_response(credential=credential, expected_challenge=base64url_to_bytes(challenge),
                                         expected_rp_id=rp_id, expected_origin=origin, require_user_verification=False)
    except Exception as e:
        raise HTTPException(400, f"passkey not accepted: {e}")
    cred = {"kind": "passkey", "id": bytes_to_base64url(v.credential_id),
            "public_key": bytes_to_base64url(v.credential_public_key), "sign_count": v.sign_count}
    _save_cred(core, acc.id, cred)
    core.emit("passkey.registered", {"account_id": acc.id, "credential_id": cred["id"], "kind": "passkey",
                                     "public_key": cred["public_key"]})
    return {"credential_id": cred["id"]}


def signing_options(core: Core, request: Request, acc: Account, terms_digest_hex: str) -> dict:
    rp_id, _ = rp(core, request)
    allow = [PublicKeyCredentialDescriptor(id=base64url_to_bytes(c["id"]))
             for c in credentials(core, acc.id) if c["kind"] == "passkey"]
    opts = generate_authentication_options(rp_id=rp_id, challenge=bytes.fromhex(terms_digest_hex),
                                           allow_credentials=allow,
                                           user_verification=UserVerificationRequirement.PREFERRED)
    return json.loads(options_to_json(opts))


def verify_passkey_signature(core: Core, request: Request, acc: Account, terms_digest_hex: str,
                             assertion: dict) -> dict:
    rp_id, origin = rp(core, request)
    cred = next((c for c in credentials(core, acc.id) if c["id"] == assertion.get("id")), None)
    if cred is None:
        raise HTTPException(400, "unknown passkey")
    try:
        v = verify_authentication_response(credential=assertion, expected_challenge=bytes.fromhex(terms_digest_hex),
                                           expected_rp_id=rp_id, expected_origin=origin,
                                           credential_public_key=base64url_to_bytes(cred["public_key"]),
                                           credential_current_sign_count=cred["sign_count"],
                                           require_user_verification=False)
    except Exception as e:
        raise HTTPException(400, f"signature not accepted: {e}")
    cred["sign_count"] = v.new_sign_count
    _save_cred(core, acc.id, cred)
    r = assertion.get("response", {})
    return {"kind": "passkey", "credential_id": cred["id"], "challenge": terms_digest_hex,
            "authenticator_data": r.get("authenticatorData"), "client_data_json": r.get("clientDataJSON"),
            "signature": r.get("signature"), "user_verified": v.user_verified}


# ----------------------------------------------------------------------------- device keys

def register_device_key(core: Core, acc: Account, jwk: dict) -> dict:
    if jwk.get("kty") != "EC" or jwk.get("crv") != "P-256" or "d" in jwk:
        raise HTTPException(400, "expected a public P-256 key")
    cid = "dk_" + hashlib.sha256((jwk["x"] + jwk["y"]).encode()).hexdigest()[:16]
    _save_cred(core, acc.id, {"kind": "device", "id": cid, "jwk": {"kty": "EC", "crv": "P-256", "x": jwk["x"],
                                                                     "y": jwk["y"]}, "sign_count": 0})
    core.emit("passkey.registered", {"account_id": acc.id, "credential_id": cid, "kind": "device",
                                     "public_key": json.dumps({"x": jwk["x"], "y": jwk["y"]})})
    return {"credential_id": cid}


def verify_device_signature(core: Core, acc: Account, terms_digest_hex: str, credential_id: str,
                            signature_b64u: str) -> dict:
    cred = next((c for c in credentials(core, acc.id) if c["id"] == credential_id and c["kind"] == "device"), None)
    if cred is None:
        raise HTTPException(400, "unknown device key")
    x = int.from_bytes(base64url_to_bytes(cred["jwk"]["x"]), "big")
    y = int.from_bytes(base64url_to_bytes(cred["jwk"]["y"]), "big")
    pub = ec.EllipticCurvePublicNumbers(x, y, ec.SECP256R1()).public_key()
    raw = base64url_to_bytes(signature_b64u)
    if len(raw) != 64:
        raise HTTPException(400, "expected a raw P-256 signature")
    der = encode_dss_signature(int.from_bytes(raw[:32], "big"), int.from_bytes(raw[32:], "big"))
    try:
        pub.verify(der, bytes.fromhex(terms_digest_hex), ec.ECDSA(hashes.SHA256()))
    except InvalidSignature:
        raise HTTPException(400, "signature does not match these terms")
    return {"kind": "device", "credential_id": credential_id, "challenge": terms_digest_hex,
            "signature": signature_b64u}
